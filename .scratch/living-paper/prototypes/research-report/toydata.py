"""PROTOTYPE, throwaway: loads the toy's M7 results for the research-report prototype.

Reads ~/wayline-m7/toy (or $TOY) in place and never writes there. Every number the reports
quote comes from here, and `python3 toydata.py` checks this loader against the run's own
analysis files (analysis/ablation/signal-<s>.json) before anything is drawn.
"""

import json
import math
import os
import random
import sys
from functools import lru_cache
from pathlib import Path

TOY = Path(os.environ.get("TOY", Path.home() / "wayline-m7" / "toy"))
SIGNALS = (1, 2, 4, 8)
SEEDS = tuple(range(1, 11))
ARMS = ("raw", "raw_x1x2", "raw_x3x4", "raw_allpairs")
ARM_LABEL = {
    "raw": "raw",
    "raw_x1x2": "raw + x1·x2",
    "raw_x3x4": "raw + x3·x4",
    "raw_allpairs": "raw + all pairs",
}
# contrast -> (arm a, arm b): per seed, auroc(a) - auroc(b) on the same draw
CONTRASTS = {
    "paired_gain": ("raw_x3x4", "raw"),
    "credit_margin": ("raw_x3x4", "raw_x1x2"),
    "allpairs_cost": ("raw_allpairs", "raw_x3x4"),
    "wrong_pair_vs_raw": ("raw_x1x2", "raw"),
    "allpairs_vs_raw": ("raw_allpairs", "raw"),
}
TARGET = 0.82


@lru_cache(maxsize=None)
def summary(signal, arm, seed):
    path = TOY / "results" / "ablation" / f"signal-{signal}" / arm / f"seed-{seed}" / "summary.json"
    return json.loads(path.read_text())


@lru_cache(maxsize=None)
def analysis(signal):
    return json.loads((TOY / "analysis" / "ablation" / f"signal-{signal}.json").read_text())


def auroc(signal, arm, seed):
    return summary(signal, arm, seed)["auroc"]


def contrast(name, signal):
    a, b = CONTRASTS[name]
    return [auroc(signal, a, s) - auroc(signal, b, s) for s in SEEDS]


def bootstrap_means(values, resamples=10000, seed=0):
    """The toy's own procedure (src/toy/stats.py:bootstrap_mean_ci): sorted resampled means."""
    rng = random.Random(seed)
    k = len(values)
    return sorted(sum(rng.choices(values, k=k)) / k for _ in range(resamples))


def ci95(values):
    means = bootstrap_means(values)
    r = len(means)
    return means[round(0.025 * (r - 1))], means[round(0.975 * (r - 1))]


def ceiling(signal):
    return analysis(signal)["ceiling"]["values"]


def delong(signal, pair):
    return analysis(signal)["delong"][pair]


@lru_cache(maxsize=None)
def held_out_rows(seed, signal):
    """The seed's held-out rows, regenerated by the toy's own generator (stdlib)."""
    sys.path.insert(0, str(TOY / "src"))
    from toy.generate import generate

    _, held = generate(seed, signal=float(signal), rows=20000)
    return held


def oracle_score(row):
    return 0.6 * row["x1"] - 0.4 * row["x2"] + 1.1 * row["x3"] * row["x4"]


def logit(p):
    p = min(max(p, 1e-9), 1 - 1e-9)
    return math.log(p / (1 - p))


def check():
    """Every contrast, interval, and ceiling here equals the run's analysis files."""
    bad = 0
    for s in SIGNALS:
        a = analysis(s)
        for name in CONTRASTS:
            vals = contrast(name, s)
            lo, hi = ci95(vals)
            ref = a[name]
            if abs(sum(vals) / 10 - ref["mean"]) > 1e-12 or abs(lo - ref["ci95"][0]) > 1e-12 or abs(hi - ref["ci95"][1]) > 1e-12:
                bad += 1
                print("MISMATCH", s, name)
        held = held_out_rows(1, s)
        labels = [r["y"] for r in held]
        if labels != summary(s, "raw_x3x4", 1)["held_out_labels"]:
            bad += 1
            print("MISMATCH held-out labels", s)
    print("checked", len(SIGNALS) * len(CONTRASTS), "intervals and", len(SIGNALS), "held-out splits:", "ok" if not bad else f"{bad} mismatches")
    return bad


if __name__ == "__main__":
    sys.exit(1 if check() else 0)
